$ErrorActionPreference = 'Stop'
$Repository = 'I:/FModel'
$Destination = 'I:/PBZ/Releases/fmodel-json-export'
$metaPath = Join-Path $Destination 'build-info.json'
$meta = Get-Content $metaPath -Raw | ConvertFrom-Json
if ($meta.toolVersion -ne '4.4.4-json-export-1' -or !$meta.selfContained) { throw 'Refusing to replace a release not generated by this implementation.' }
$oldHash = (Get-FileHash 'I:/PBZ/FModel.exe' -Algorithm SHA256).Hash
$planHash = (Get-FileHash 'I:/PBZ/.agent/fmodel-json-export-automation/task-item.md').Hash
$commit = (& git -C $Repository rev-parse HEAD).Trim()
$arguments = @('-c','Release','-r','win-x64','--self-contained','true','-p:PublishSingleFile=true','-p:IncludeNativeLibrariesForSelfExtract=true','-p:CUE4PARSE_SKIP_NATIVE=true','-p:Version=4.4.4.1','-p:FileVersion=4.4.4.1',"-p:InformationalVersion=4.4.4.1+$commit-json-export-1",'-o',$Destination)
foreach ($project in @('FModel/FModel.csproj','FModel.Cli/FModel.Cli.csproj')) {
    & dotnet publish (Join-Path $Repository $project) @arguments
    if ($LASTEXITCODE -ne 0) { throw "Final publish failed: $project" }
}
& dotnet run --project (Join-Path $Repository 'FModel.Export.Tests/FModel.Export.Tests.csproj') -c Release -p:CUE4PARSE_SKIP_NATIVE=true -- --cli (Join-Path $Destination 'FModel.Cli.exe')
if ($LASTEXITCODE -ne 0) { throw 'Published binary regression tests failed' }
$settingsPath = Join-Path $env:APPDATA 'FModel/AppSettings.json'
$settingsBytes = [IO.File]::ReadAllBytes($settingsPath)
$existing = @(Get-Process FModel -ErrorAction SilentlyContinue)
$guiStatus = 'not-run-existing-instance'
if ($existing.Count -eq 0) {
    $process = $null
    try {
        $process = Start-Process (Join-Path $Destination 'FModel.exe') -WorkingDirectory $Destination -PassThru
        Start-Sleep -Seconds 8
        $process.Refresh()
        if ($process.HasExited) { throw 'New GUI exited unexpectedly during smoke test' }
        if (!$process.MainWindowTitle.Contains('FModel')) { throw "GUI main window not verified: $($process.MainWindowTitle)" }
        $guiStatus = 'main-window-started'
        $process.CloseMainWindow() | Out-Null
        if (!$process.WaitForExit(10000)) { Stop-Process -Id $process.Id }
    }
    finally {
        if ($process -and !$process.HasExited) { Stop-Process -Id $process.Id -ErrorAction SilentlyContinue }
        [IO.File]::WriteAllBytes($settingsPath, $settingsBytes)
    }
}
if ((Get-FileHash 'I:/PBZ/FModel.exe').Hash -ne $oldHash) { throw 'Old binary changed unexpectedly' }
if ((Get-FileHash 'I:/PBZ/.agent/fmodel-json-export-automation/task-item.md').Hash -ne $planHash) { throw 'Plan changed unexpectedly' }
$hashes = @()
foreach ($name in @('FModel.exe','FModel.Cli.exe','.data/oodle-data-shared.dll','.data/zlib-ng2.dll')) {
    $file = Join-Path $Destination $name
    $hashes += [ordered]@{file=$name; sha256=(Get-FileHash $file -Algorithm SHA256).Hash; bytes=(Get-Item $file).Length}
}
$meta.files = $hashes
$meta.publishedUtc = [DateTime]::UtcNow.ToString('o')
[IO.File]::WriteAllText($metaPath, ($meta | ConvertTo-Json -Depth 6), [Text.UTF8Encoding]::new($false))
$evidence = [ordered]@{guiSmoke=$guiStatus; oldExeUnchanged=$true; planUnchanged=$true; oldVersion=(Get-Item 'I:/PBZ/FModel.exe').VersionInfo.FileVersion; newVersion=(Get-Item (Join-Path $Destination 'FModel.exe')).VersionInfo.FileVersion; cliVersion=(Get-Item (Join-Path $Destination 'FModel.Cli.exe')).VersionInfo.FileVersion; regressionTests='core/configuration/CLI published-binary checks'; publishedUtc=[DateTime]::UtcNow.ToString('o')}
[IO.File]::WriteAllText((Join-Path $Destination 'validation.json'), ($evidence | ConvertTo-Json -Depth 4), [Text.UTF8Encoding]::new($false))
Copy-Item (Join-Path $Repository 'Docs/json-export.md') (Join-Path $Destination 'README.md') -Force
$source = 'I:/PBZ/Releases/fmodel-json-export-source'
New-Item -ItemType Directory -Path $source -Force | Out-Null
$files = @(& git -C $Repository diff --name-only)
$files += @(& git -C $Repository ls-files --others --exclude-standard | Where-Object { ($_ -like 'FModel.Export/*' -or $_ -like 'FModel.Cli/*' -or $_ -like 'FModel.Export.Tests/*' -or $_ -like 'FModel.Export.Benchmarks/*' -or $_ -eq 'FModel/Services/BulkJsonExport.cs' -or $_ -eq 'Docs/json-export.md' -or $_ -eq 'Scripts/Publish-JsonExport.ps1') -and $_ -notmatch '/(bin|obj)/' })
foreach ($relative in ($files | Select-Object -Unique)) {
    $target = Join-Path $source $relative
    New-Item -ItemType Directory -Path (Split-Path $target) -Force | Out-Null
    Copy-Item (Join-Path $Repository $relative) $target
}
$patch = (& git -C $Repository diff --no-ext-diff | Out-String)
[IO.File]::WriteAllText((Join-Path $source 'tracked-changes.patch'), $patch, [Text.UTF8Encoding]::new($false))
Copy-Item (Join-Path $Repository 'LICENSE') (Join-Path $source 'LICENSE')
Copy-Item (Join-Path $Repository 'NOTICE') (Join-Path $source 'NOTICE')
$readme = "Base repository: BosonHBC/FModel, branch pbz/nov-2026, commit $commit.`r`nSubmodule revisions are unchanged. Copy these source files over a recursive checkout of that base. The patch covers tracked files; complete added source is included. No AES key, usmap or game assets are included.`r`nBuild and usage: Docs/json-export.md. Reusable publish script: Scripts/Publish-JsonExport.ps1 (use a new destination).`r`n"
[IO.File]::WriteAllText((Join-Path $source 'README-source.txt'), $readme, [Text.UTF8Encoding]::new($false))
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = 'I:/PBZ/Releases/fmodel-json-export-win-x64.zip'
$sourceZip = 'I:/PBZ/Releases/fmodel-json-export-source.zip'
[IO.Compression.ZipFile]::CreateFromDirectory($Destination, $zip, [IO.Compression.CompressionLevel]::Optimal, $true)
[IO.Compression.ZipFile]::CreateFromDirectory($source, $sourceZip, [IO.Compression.CompressionLevel]::Optimal, $false)
$archive = [IO.Compression.ZipFile]::OpenRead($zip)
try {
    $names = @($archive.Entries | ForEach-Object FullName)
    foreach ($required in @('FModel.exe','FModel.Cli.exe','.data/oodle-data-shared.dll','.data/zlib-ng2.dll')) {
        if (@($names | Where-Object { $_.Replace('\','/').EndsWith($required) }).Count -ne 1) { throw "Incomplete runtime archive: $required" }
    }
}
finally { $archive.Dispose() }
Write-Output ($evidence | ConvertTo-Json)
Write-Output "Runtime ZIP: $zip"
Write-Output "Source ZIP: $sourceZip"
